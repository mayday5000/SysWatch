#!/usr/bin/env bash
# Refactor v1.5 deploy: detect compiler/arch, emit syscall_names.inc and filters.xml,
# build userspace and the kernel module, load the module. Does not start the TUI.
#   ./deploy.sh            build both, load the module
#   ./deploy.sh --no-run   build only
set -euo pipefail
cd "$(dirname "$0")"

BOLD="\033[1m"; GREEN="\033[32m"; YELLOW="\033[33m"; RED="\033[31m"; RESET="\033[0m"
log_info() { echo -e "${BOLD}${GREEN}[INFO]${RESET} $1"; }
log_warn() { echo -e "${BOLD}${YELLOW}[WARN]${RESET} $1"; }
log_err()  { echo -e "${BOLD}${RED}[ERROR]${RESET} $1" >&2; }

MODULE_NAME="syscall_monitor"
UDEV_RULE_FILE="/etc/udev/rules.d/99-${MODULE_NAME}.rules"
BUILD_DIR="build"
NO_RUN=0
for arg in "$@"; do
    [[ "$arg" == "--no-run" ]] && NO_RUN=1
done

ensure_pkg() {
    local bin="$1" pkg="$2"
    if command -v "$bin" >/dev/null 2>&1; then
        log_info "$bin already installed"
        return 0
    fi
    log_info "installing $pkg"
    if command -v apt-get >/dev/null 2>&1; then
        sudo apt-get update && sudo apt-get install -y "$pkg"
    elif command -v dnf >/dev/null 2>&1; then
        sudo dnf install -y "$pkg"
    elif command -v yum >/dev/null 2>&1; then
        sudo yum install -y "$pkg"
    else
        log_warn "no package manager; install $pkg manually"
        return 1
    fi
}

emit_syscall_names() {
    local cxx="$1" arch="$2" out="syscall_names.inc"
    local header="" probe=""
    # awk exits after the first header. Without || true, pipefail treats
    # the resulting SIGPIPE from the compiler as a failed script.
    probe=$(printf '#include <asm/unistd.h>\n' | "$cxx" -H -E -x c++ -o /dev/null - 2>&1 || true)
    header=$(printf '%s\n' "$probe" | awk '/\.h/ {print $2; exit}')
    log_info "compiler ${cxx}, arch ${arch}, unistd ${header:-missing}"
    {
        echo "/* generated by deploy.sh from the compiler include path */"
        echo "static const char *const kSyscallNames[] = {"
        if [[ -n "${header}" && -f "$header" ]]; then
            local dir
            dir=$(dirname "$header")
            grep -hE '^[[:space:]]*#define[[:space:]]+__NR_[A-Za-z0-9_]+[[:space:]]+[0-9]+' \
                "$header" "$dir"/*.h 2>/dev/null \
                | sed -E 's/.*__NR_([A-Za-z0-9_]+).*/"\1",/' \
                | awk '!seen[$0]++' || true
        else
            echo '"read", "write", "openat", "close", "mmap", "execve", "poll", "ioctl",'
        fi
        echo "};"
    } > "$out"
    log_info "wrote ${out}"
}

running() {
    ps -eo comm= 2>/dev/null | awk -v n="$1" '$0==n {found=1} END {exit !found}'
}

emit_filters() {
    local out="filters.xml"
    local -a procs=()
    local term="${TERM_PROGRAM:-}${TERMINAL:-}"
    for name in gnome-terminal gnome-terminal-server konsole xterm kitty alacritty \
                tilix terminator xfce4-terminal mate-terminal lxterminal wezterm foot; do
        if running "$name" || [[ "$term" == *"$name"* ]]; then
            procs+=("$name")
        fi
    done
    for name in gnome-shell plasmashell kwin_x11 kwin_wayland Xorg Xwayland vmtoolsd VBoxClient; do
        if running "$name"; then
            procs+=("$name")
        fi
    done
    {
        echo '<?xml version="1.0"?>'
        echo '<filters>'
        echo '  <!-- written by deploy.sh from this session -->'
        local p
        for p in "${procs[@]}"; do
            echo "  <hide kind=\"process\">${p}</hide>"
        done
        echo '  <hide kind="sysid">0</hide>'
        echo '</filters>'
    } > "$out"
    log_info "wrote ${out} (${#procs[@]} processes)"
}

ensure_pkg cmake cmake
ensure_pkg g++ g++ || ensure_pkg clang++ clang
ensure_pkg lsof lsof || true
ensure_pkg make build-essential || true

CXX_BIN="g++"
command -v g++ >/dev/null 2>&1 || CXX_BIN="clang++"
if ! command -v "$CXX_BIN" >/dev/null 2>&1; then
    log_err "no C++ compiler"
    exit 1
fi

ARCH_NAME=$(uname -m)
log_info "generating syscall names"
emit_syscall_names "$CXX_BIN" "$ARCH_NAME" || log_warn "syscall name probe failed; keeping existing list"
log_info "writing filters.xml"
emit_filters || log_warn "filter probe failed; keeping existing filters.xml"

log_info "removing old objects"
rm -f ./*.o ./*.cmd ./*.ko ./*.mod ./*.mod.c ./Module.symvers ./modules.order
rm -f "${BUILD_DIR}"/*.o "${BUILD_DIR}"/*.cmd "${BUILD_DIR}"/*.ko \
      "${BUILD_DIR}"/*.mod "${BUILD_DIR}"/*.mod.c \
      "${BUILD_DIR}"/Module.symvers "${BUILD_DIR}"/modules.order
rm -rf "${BUILD_DIR}"/.tmp_versions

log_info "configuring userspace"
cmake -B "${BUILD_DIR}" -DCMAKE_BUILD_TYPE=Release
CORES=$(nproc 2>/dev/null || echo 2)
log_info "building userspace with ${CORES} cores"
cmake --build "${BUILD_DIR}" --config Release -j "${CORES}"

log_info "building kernel module into ./build"
if [[ -d "/lib/modules/$(uname -r)/build" ]]; then
    make module
else
    log_warn "kernel headers missing; module not built"
fi

if [[ "$NO_RUN" -eq 1 ]]; then
    log_info "build only"
    exit 0
fi

if [[ ! -f ${BUILD_DIR}/${MODULE_NAME}.ko ]]; then
    log_warn "no ${BUILD_DIR}/${MODULE_NAME}.ko; TUI can still run in simulator mode"
    exit 0
fi

# Older versions installed a udev rule that made the node world-readable
# (0666). The stream exposes every process's syscalls, so remove it and
# keep the kernel default: root-only 0600, and CAP_PERFMON/CAP_SYS_ADMIN
# is checked again in open().
if [[ -f "${UDEV_RULE_FILE}" ]]; then
    log_info "removing legacy world-readable udev rule ${UDEV_RULE_FILE}"
    sudo rm -f "${UDEV_RULE_FILE}"
    sudo udevadm control --reload-rules || true
fi
if grep -q "^${MODULE_NAME} " /proc/modules 2>/dev/null; then
    log_info "unloading existing ${MODULE_NAME}"
    sudo rmmod "${MODULE_NAME}" || true
fi
log_info "insmod ${BUILD_DIR}/${MODULE_NAME}.ko"
sudo insmod "${BUILD_DIR}/${MODULE_NAME}.ko"
log_info "installed. next: sudo ./${BUILD_DIR}/syswatch"
